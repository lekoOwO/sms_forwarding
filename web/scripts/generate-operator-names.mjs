import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { buildOperatorNames } from "./operator-names-generator.mjs";

const inputUrl = new URL("../data/mcc-mnc-list.json", import.meta.url);
const metadataUrl = new URL("../data/mcc-mnc-list.metadata.json", import.meta.url);
const outputUrl = new URL("../src/lib/operator-names.generated.js", import.meta.url);

const input = await readFile(inputUrl);
const sourceHash = createHash("sha256").update(input).digest("hex");
const metadata = JSON.parse(await readFile(metadataUrl, "utf8"));
if (metadata.sourceSha256 !== sourceHash) throw new Error("MCC/MNC source hash does not match metadata");
const rows = JSON.parse(input);
if (metadata.rowCount !== rows.length) throw new Error("MCC/MNC source row count does not match metadata");

const names = buildOperatorNames(rows);
const body = JSON.stringify(names, null, "\t");
const output = `// Generated by web/scripts/generate-operator-names.mjs; do not edit by hand.\n// Source: ${metadata.sourceUrl} @ ${metadata.sourceCommit}\n// Source JSON SHA-256: ${sourceHash}\n// Data attribution: Wikipedia contributors, CC BY-SA 4.0; see web/data/NOTICE.md.\n/** @type {Readonly<Record<string, string>>} */\nexport const OPERATOR_NAMES = Object.freeze(${body});\n`;

if (process.argv.includes("--check")) {
	const current = await readFile(outputUrl, "utf8").catch(() => "");
	if (current !== output) throw new Error("Operator names are out of date; run: npm --prefix web run generate:operator-names");
} else {
	await writeFile(outputUrl, output);
	console.log(`Operator names: ${Object.keys(names).length} valid MCC/MNC codes from ${rows.length} source rows`);
}
